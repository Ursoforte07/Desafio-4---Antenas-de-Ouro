DROP VIEW IF EXISTS vw_dashboard CASCADE;
DROP VIEW IF EXISTS vw_resumo_turmas CASCADE;
DROP VIEW IF EXISTS vw_linhas_alunos CASCADE;

DROP TABLE IF EXISTS frequencias CASCADE;
DROP TABLE IF EXISTS aulas CASCADE;
DROP TABLE IF EXISTS matriculas CASCADE;
DROP TABLE IF EXISTS alunos CASCADE;
DROP TABLE IF EXISTS turmas CASCADE;
DROP TABLE IF EXISTS professores CASCADE;

CREATE TABLE professores (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  senha_hash TEXT NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE turmas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  codigo TEXT NOT NULL UNIQUE,
  horario TEXT NOT NULL,
  professor_id INTEGER REFERENCES professores(id) ON DELETE SET NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE alunos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE matriculas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aluno_id INTEGER NOT NULL REFERENCES alunos(id) ON DELETE CASCADE,
  turma_id INTEGER NOT NULL REFERENCES turmas(id) ON DELETE CASCADE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_matricula_aluno_turma UNIQUE (aluno_id, turma_id)
);

CREATE TABLE aulas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turma_id INTEGER NOT NULL REFERENCES turmas(id) ON DELETE CASCADE,
  data DATE NOT NULL,
  horario TEXT NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_aula_turma_data_horario UNIQUE (turma_id, data, horario)
);

CREATE TABLE frequencias (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aula_id INTEGER NOT NULL REFERENCES aulas(id) ON DELETE CASCADE,
  aluno_id INTEGER NOT NULL REFERENCES alunos(id) ON DELETE CASCADE,
  presente BOOLEAN NOT NULL DEFAULT true,
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_frequencia_aula_aluno UNIQUE (aula_id, aluno_id)
);

CREATE INDEX idx_turmas_professor_id ON turmas(professor_id);
CREATE INDEX idx_matriculas_aluno_id ON matriculas(aluno_id);
CREATE INDEX idx_matriculas_turma_id ON matriculas(turma_id);
CREATE INDEX idx_aulas_turma_id ON aulas(turma_id);
CREATE INDEX idx_aulas_data ON aulas(data);
CREATE INDEX idx_frequencias_aula_id ON frequencias(aula_id);
CREATE INDEX idx_frequencias_aluno_id ON frequencias(aluno_id);
CREATE INDEX idx_alunos_nome ON alunos(LOWER(nome));
